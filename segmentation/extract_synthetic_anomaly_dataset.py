"""
Extracts the single bees from the synthetic images with varroa and generates
the per-bee anomaly mask for the anomaly detection metrics.

Pipeline:
1. Load the synthetic image and the varroa GT mask (generated by varroa_generator.py)
2. Use YOLO model inference to find and crop each bee
3. Extract the mask of the raw bee polygon
4. Pass the raw image and the mask to dataset_cleaning.clean_bee for the unified cleaning, rotation and edge-feathering pipeline
5. Intersect the cleaned varroa GT mask with the new image
6. Save:
   - The bee crop (512x512, black background, smoothly feathered and oriented)
   - The per-bee anomaly mask (512x512, white=varroa, black=normal)
   - A label (0=normal, 1=anomalous) in a CSV file
"""

from bee_paths import DATA_ROOT
import os
import cv2
import csv
import numpy as np
from ultralytics import YOLO
# Import the updated function from the new, optimised cleaning script
from dataset_cleaning import TARGET_SIZE, clean_bee
from bee_orientation import HeadOrienter


# --- Configuration ---
# Folder with the synthetic images and masks generated by varroa_generator.py
SYNTHETIC_DIR = DATA_ROOT + "/processed/test_batch3+4/synthetic_varroa_output/images"

# YOLO segmentation model (the same one used in extract_anomaly_dataset.py)
YOLO_MODEL_PATH = "runs/segment/runs/segment/bee_model_finetuned_yolo26s_batch3+4_img1440/weights/best.pt"

# Output
OUTPUT_BASE = DATA_ROOT + "/processed/test_single_bee_batch3+4_varroa/images"
OUTPUT_NORMAL = os.path.join(OUTPUT_BASE, "normal")
OUTPUT_ANOMALOUS = os.path.join(OUTPUT_BASE, "anomalous")
OUTPUT_MASKS = os.path.join(OUTPUT_BASE, "masks")

# Generous initial padding so the bee is not cut off during rotations and cleaning
PADDING = 30

# Minimum number of varroa pixels to consider the bee anomalous
# (avoids false positives from a 1-2 pixel overlap at the border)
MIN_VARROA_PIXELS = 10


def crop_raw_bee(image, varroa_full_mask, polygon_pts, bbox):
    """
    Extracts the raw crop of the bee and of the varroa mask.
    Applies no morphological operations (they are done by dataset_cleaning).
    """
    h, w = image.shape[:2]
    bx, by, bw, bh = bbox

    # Create the raw mask of the bee polygon (full size)
    bee_mask = np.zeros((h, w), dtype=np.uint8)
    pts = polygon_pts.astype(np.int32).reshape((-1, 1, 2))
    cv2.fillPoly(bee_mask, [pts], 255)

    # Bounding box with generous padding to allow later rotations during cleaning
    x1 = max(0, bx - PADDING)
    y1 = max(0, by - PADDING)
    x2 = min(w, bx + bw + PADDING)
    y2 = min(h, by + bh + PADDING)

    # Crop
    img_crop = image[y1:y2, x1:x2].copy()
    bee_mask_crop = bee_mask[y1:y2, x1:x2].copy()
    varroa_mask_crop = varroa_full_mask[y1:y2, x1:x2].copy()

    return img_crop, bee_mask_crop, varroa_mask_crop


def process_synthetic_image(syn_img_path, mask_path, model, orienter):
    """
    Processes a single synthetic image: extracts all the bees and classifies them
    as normal or anomalous based on their overlap with the varroa mask.
    Fully integrates the dataset_cleaning pipeline.
    """
    syn_img = cv2.imread(syn_img_path)
    varroa_mask = cv2.imread(mask_path, cv2.IMREAD_GRAYSCALE)

    if syn_img is None:
        print(f"  ✗ Could not load: {syn_img_path}")
        return [], 0
    if varroa_mask is None:
        print(f"  ✗ Could not load mask: {mask_path}")
        return [], 0

    # Binarise the mask (it may have JPEG artefacts)
    _, varroa_mask = cv2.threshold(varroa_mask, 128, 255, cv2.THRESH_BINARY)

    # YOLO inference (same parameters as extract_anomaly_dataset.py)
    results = model.predict(source=syn_img, save=False, show=False, conf=0.35, imgsz=1920, max_det=2000)
    
    detections = []
    if len(results) > 0 and results[0].masks is not None:
        res = results[0]
        boxes = res.boxes.xyxy.cpu().numpy().astype(int)
        for i, box in enumerate(boxes):
            polygon = res.masks.xy[i]
            if len(polygon) == 0:
                continue
            x1, y1, x2, y2 = box
            detections.append({
                "polygon": polygon,
                "bbox": (x1, y1, x2 - x1, y2 - y1),
                "conf": res.boxes.conf.cpu().numpy()[i]
            })

    base_name = os.path.splitext(os.path.basename(syn_img_path))[0]
    processed_results = []
    discarded = 0

    for i, det in enumerate(detections):
        # 1. Extract the raw crop (image, bee mask, varroa mask)
        img_crop, bee_mask_crop, varroa_mask_crop = crop_raw_bee(
            syn_img, varroa_mask, det["polygon"], det["bbox"]
        )


        # 2. Clean and normalise the bee with the dataset_cleaning pipeline.
        #    clean_bee also returns the affine it used (crop -> final frame): we
        #    apply it to the varroa mask, which thus stays aligned with the bee
        #    (even when the bee is rotated by 180° to have the head at the top).
        result = clean_bee(img_crop, bee_mask_crop, is_raw_polygon=True, orienter=orienter)
        if result.image is None:
            discarded += 1
            continue
        cleaned_bee = result.image

        varroa_final_mask = cv2.warpAffine(varroa_mask_crop, result.matrix, (TARGET_SIZE, TARGET_SIZE),
                                           flags=cv2.INTER_NEAREST, borderValue=0)

        # Intersection with the final bee mask (varroa outside the bee is ignored)
        varroa_final_mask = cv2.bitwise_and(varroa_final_mask, result.mask)

        # Recount the actual varroa pixels left in the transformed mask
        n_px = cv2.countNonZero(varroa_final_mask)
        is_anomalous = n_px >= MIN_VARROA_PIXELS
        
        processed_results.append((cleaned_bee, varroa_final_mask, is_anomalous, base_name, i))

    return processed_results, discarded


def main():
    print(" Loading the YOLO model...")
    model = YOLO(YOLO_MODEL_PATH)
    orienter = HeadOrienter()
    
    # Create the output folders
    for d in [OUTPUT_NORMAL, OUTPUT_ANOMALOUS, OUTPUT_MASKS]:
        os.makedirs(d, exist_ok=True)

    # Find all the (synthetic image, GT mask) pairs
    syn_files = sorted([
        f for f in os.listdir(SYNTHETIC_DIR)
        if f.endswith(".jpg") and "_syn" in f
    ])

    if not syn_files:
        print(f"No synthetic images found in {SYNTHETIC_DIR}")
        return

    csv_rows = []
    total_normal = 0
    total_anomalous = 0
    total_discarded = 0

    mask_dir = os.path.join(os.path.dirname(SYNTHETIC_DIR), "masks")

    for syn_file in syn_files:
        # Derive mask filename: DSC_4914_syn_0.jpg → DSC_4914_mask_0.png
        mask_file = syn_file.replace("_syn", "_mask").replace(".jpg", ".png")
        syn_path = os.path.join(SYNTHETIC_DIR, syn_file)
        mask_path = os.path.join(mask_dir, mask_file)

        if not os.path.exists(mask_path):
            print(f"  ✗ Mask not found: {mask_path}")
            continue

        print(f"\nProcessing: {syn_file}")
        results, discarded = process_synthetic_image(syn_path, mask_path, model, orienter)
        total_discarded += discarded

        for bee_crop, varroa_crop, is_anomalous, base_name, bee_idx in results:
            bee_id = f"{base_name}_bee_{bee_idx:04d}"

            if is_anomalous:
                # Save in the anomalous folder + mask
                img_path = os.path.join(OUTPUT_ANOMALOUS, f"{bee_id}.png")
                msk_path = os.path.join(OUTPUT_MASKS, f"{bee_id}_mask.png")
                cv2.imwrite(img_path, bee_crop)
                cv2.imwrite(msk_path, varroa_crop)
                csv_rows.append([bee_id, 1, img_path, msk_path])
                total_anomalous += 1
            else:
                # Save in the normal folder (no mask needed)
                img_path = os.path.join(OUTPUT_NORMAL, f"{bee_id}.png")
                cv2.imwrite(img_path, bee_crop)
                csv_rows.append([bee_id, 0, img_path, ""])
                total_normal += 1

    # Save the CSV with all the labels
    csv_path = os.path.join(OUTPUT_BASE, "labels.csv")
    with open(csv_path, "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["bee_id", "label", "image_path", "mask_path"])
        writer.writerows(csv_rows)

    print(f"\n{'='*60}")
    print(f"✅ Extraction complete!")
    print(f"   Normal bees:    {total_normal}")
    print(f"   Anomalous bees: {total_anomalous}")
    print(f"   Bees rejected (cleaning): {total_discarded}")
    print(f"   CSV labels:   {csv_path}")
    print(f"   Output dir:   {OUTPUT_BASE}")
    print(f"{'='*60}")
    print(f"\nOutput structure:")
    print(f"  {OUTPUT_BASE}/")
    print(f"    normal/        → {total_normal} bees without varroa")
    print(f"    anomalous/     → {total_anomalous} bees with varroa")
    print(f"    masks/         → GT masks for the anomalous bees")
    print(f"    labels.csv     → bee_id, label (0/1), paths")


if __name__ == "__main__":
    main()
